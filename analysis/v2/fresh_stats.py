"""Follow-up study v2 (PROTOCOL §17, 2026-11-07 entries V1-V6): analysis on the fresh items.
For each of PopQA-LT, TriviaQA, HotpotQA (fresh test items) and PubHealth (fresh dev items 300-499): accuracy, H@0.8 and
AURC of RAG-Verify v2, RAG-Verify v1 and the 12 baselines (seed 0), each with its pre-specified confidence score.
v2 minus each baseline: paired bootstrap CIs, McNemar / paired permutation / bootstrap p, Holm over the 12 baselines per
dataset x metric (as main_stats.py). v2 minus v1 and v1 minus each baseline are reported separately (v1 rows: Holm as well).
Writes results/analysis/fresh_stats.json and paper/generated/table_fresh.tex.
Usage: .venv/Scripts/python.exe analysis/v2/fresh_stats.py
"""
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "analysis")); sys.path.insert(0, str(ROOT / "src"))
from main_stats import BASELINES, DS_NAME, N_BOOT, answered_at, aurc_boot, load_run, metrics  # noqa: E402
from method_name import METHOD_NAME  # noqa: E402
from ragverify.metrics import holm, mcnemar_exact, paired_bootstrap, paired_permutation  # noqa: E402

DATASETS = ["popqa_lt", "triviaqa", "hotpotqa", "pubhealth"]


def load(method, ds):
    return load_run(f"fresh_{method}_{ds}", method)


def compare(a, b, idx, a_aurc_b):
    _, _, ac, as_ = a; _, _, bc, bs = b
    ah, bh = answered_at(as_, 0.8) * (1 - ac), answered_at(bs, 0.8) * (1 - bc)
    d_aurc = a_aurc_b - aurc_boot(bs, bc, idx)
    from ragverify.metrics import risk_coverage
    return ({"accuracy": paired_bootstrap(ac, bc), "halluc@0.8": paired_bootstrap(ah, bh),
             "aurc": {"diff": risk_coverage(as_, ac)[2] - risk_coverage(bs, bc)[2], "ci_low": float(np.percentile(d_aurc, 2.5)),
                      "ci_high": float(np.percentile(d_aurc, 97.5)), "n": len(ac)}},
            {"accuracy": mcnemar_exact(ac, bc)["p"], "halluc@0.8": paired_permutation(ah, bh),
             "aurc": float(min(1.0, 2 * min((d_aurc <= 0).mean(), (d_aurc >= 0).mean())))})


def main():
    res = {}
    for ds in DATASETS:
        v2, v1 = load("ragverify_v2", ds), load("ragverify", ds)
        ids = v2[1]; assert v1[1] == ids
        idx = np.random.default_rng(0).integers(0, len(ids), size=(N_BOOT, len(ids)))
        v2a, v1a = aurc_boot(v2[3], v2[2], idx), aurc_boot(v1[3], v1[2], idx)
        r = {"n": len(ids), "v2": metrics(v2[2], v2[3]), "v1": metrics(v1[2], v1[3]), "baselines": {}}
        d, p = compare(v2, v1, idx, v2a)
        for m in d: d[m]["p"] = p[m]
        r["v2_minus_v1"] = d
        pv2 = {m: {} for m in ("accuracy", "halluc@0.8", "aurc")}; pv1 = {m: {} for m in pv2}
        for bid, name, method in BASELINES:
            b = load(method, ds); assert b[1] == ids, (method, ds)
            e = {"name": name, **metrics(b[2], b[3])}
            e["v2_diff"], p2 = compare(v2, b, idx, v2a)
            e["v1_diff"], p1 = compare(v1, b, idx, v1a)
            for m in pv2: pv2[m][bid] = p2[m]; pv1[m][bid] = p1[m]
            r["baselines"][bid] = e
        for key, pv in (("v2_diff", pv2), ("v1_diff", pv1)):
            for m, pp in pv.items():
                adj = holm(pp)
                for bid in pp:
                    r["baselines"][bid][key][m].update({"p": pp[bid], "p_holm": adj[bid]})
        res[ds] = r
        print(ds, "done", flush=True)
    (ROOT / "results" / "analysis" / "fresh_stats.json").write_text(json.dumps(res, indent=1), encoding="utf-8")
    table(res)


def table(res):
    f = lambda x: f"{x:.3f}"  # noqa: E731
    s = lambda x: f"{x:+.3f}".replace("-", "$-$")  # noqa: E731
    nd = len(res)
    L = ["% generated by analysis/v2/fresh_stats.py (follow-up study v2): accuracy / H@0.8 / AURC on fresh items; "
         "best baseline by each metric; v2 (v1) - best baseline with 95% paired-bootstrap CI, * Holm p < 0.05 (12 baselines)",
         r"\begin{tabular}{@{}l" + "c" * nd + "@{}}",
         r"\toprule & " + " & ".join(f"{DS_NAME[d]} ($n$={res[d]['n']})" for d in res) + r" \\ \midrule"]
    for m, mn, better in (("accuracy", "Accuracy", max), ("halluc@0.8", "H@0.8", min), ("aurc", "AURC", min)):
        L.append(rf"\multicolumn{{{nd + 1}}}{{@{{}}l}}{{\emph{{{mn}}}}} \\")
        L.append(f"{METHOD_NAME} v2 & " + " & ".join(f(res[d]["v2"][m]) for d in res) + r" \\")
        L.append(f"{METHOD_NAME} v1 & " + " & ".join(f(res[d]["v1"][m]) for d in res) + r" \\")
        cells, d2, d1 = [], [], []
        for d in res:
            bid = better(res[d]["baselines"], key=lambda b: res[d]["baselines"][b][m])
            e = res[d]["baselines"][bid]
            cells.append(f"{f(e[m])} ({bid})")
            for key, out in (("v2_diff", d2), ("v1_diff", d1)):
                x = e[key][m]
                out.append(f"{s(x['diff'])} [{s(x['ci_low'])}, {s(x['ci_high'])}]{'$^{*}$' if x['p_holm'] < 0.05 else ''}")
        L.append("Best baseline & " + " & ".join(cells) + r" \\")
        L.append(r"v2 $-$ best & " + " & ".join(d2) + r" \\")
        L.append(r"v1 $-$ best & " + " & ".join(d1) + r" \\")
        L.append(r"\addlinespace")
    L[-1:] = [r"\bottomrule", r"\end{tabular}"]
    (ROOT / "paper" / "generated" / "table_fresh.tex").write_text("\n".join(L) + "\n", encoding="utf-8")
    # full table: every method, every dataset
    names = {"v2": f"{METHOD_NAME} v2", "v1": f"{METHOD_NAME} v1"}
    rows = [("v2", None), ("v1", None)] + [(b, res[next(iter(res))]["baselines"][b]["name"]) for b in res[next(iter(res))]["baselines"]]
    F = ["% generated by analysis/v2/fresh_stats.py: all methods on the fresh items (accuracy / H@0.8 / AURC); "
         "markers on baseline rows: + v2 significantly better, - v2 significantly worse (Holm, 12 baselines)",
         r"\begin{tabular}{@{}l" + "ccc" * nd + "@{}}", r"\toprule",
         " & " + " & ".join(rf"\multicolumn{{3}}{{c}}{{{DS_NAME[d]}}}" for d in res) + r" \\",
         " & " + " & ".join(["Acc & H@.8 & AURC"] * nd) + r" \\ \midrule"]
    for key, nm in rows:
        cells = []
        for d in res:
            r = res[d]
            for m in ("accuracy", "halluc@0.8", "aurc"):
                if key in ("v2", "v1"):
                    cells.append(f(r[key][m])); continue
                e = r["baselines"][key]; x = e["v2_diff"][m]; mk = ""
                if x["p_holm"] < 0.05:
                    good = x["diff"] > 0 if m == "accuracy" else x["diff"] < 0
                    mk = "$^{+}$" if good else "$^{-}$"
                cells.append(f(e[m]) + mk)
        label = names.get(key) or f"{key} {nm}"
        F.append(label + " & " + " & ".join(cells) + r" \\")
        if key == "v1": F.append(r"\midrule")
    F += [r"\bottomrule", r"\end{tabular}"]
    (ROOT / "paper" / "generated" / "table_fresh_full.tex").write_text("\n".join(F) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()

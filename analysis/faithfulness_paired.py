"""Post-hoc P3 (PROTOCOL §17 entry of 2026-11-07): paired faithfulness comparison.

Re-scores, with both faithfulness judges, the answered items of RAG-Verify, B3, B5, B6 and B8 on the four QA test sets
(same answer statements and evidence definitions as analysis/faithfulness.py), storing per-item scores. For each baseline,
the unsupported rate (score < 0.5) of RAG-Verify minus baseline is computed on the items answered by BOTH methods, each
judged against its own evidence, with a paired bootstrap 95% CI (10,000 resamples, seed 0); Holm over the 4 baselines per
dataset x judge. GPU with the same thermal wait as faithfulness.py; resumable (per-item scores saved after each method).
Outputs: results/analysis/faithfulness_items.json, results/analysis/faithfulness_paired.json,
paper/generated/table_faithfulness_paired.tex.
Usage: .venv/Scripts/python.exe analysis/faithfulness_paired.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "analysis"))
sys.path.insert(0, str(ROOT / "src"))
import faithfulness as F  # noqa: E402
from main_stats import DS_NAME  # noqa: E402
from method_name import METHOD_NAME  # noqa: E402
from ragverify.metrics import holm, paired_bootstrap  # noqa: E402

METHODS = [("rag_rerank", "B3 RAG + reranker"), ("crag", "B5 CRAG"), ("chain_of_note", "B6 Chain-of-Note"), ("selfrag", "B8 Self-RAG")]
ITEMS = ROOT / "results" / "analysis" / "faithfulness_items.json"


def score_all() -> dict:
    res = json.loads(ITEMS.read_text()) if ITEMS.exists() else {}
    work = {ds: F.build(ds) for ds in F.DATASETS}
    for ev in F.EVALUATORS:
        todo = [(ds, m) for ds in F.DATASETS for m in ["ragverify"] + [x for x, _ in METHODS] if m not in res.get(ev, {}).get(ds, {})]
        if not todo:
            continue
        model = F.V.make(ev, device="cuda", batch_size=16)
        for ds, m in todo:
            rows = work[ds][m]
            scores = []
            for s in range(0, len(rows), F.BATCH):
                F.wait_cool()
                chunk = rows[s:s + F.BATCH]
                with_doc = [(d, c) for _, d, c in chunk if d]
                it = iter(model.score([d for d, _ in with_doc], [c for _, c in with_doc]) if with_doc else [])
                scores += [float(next(it)) if d else 0.0 for _, d, _ in chunk]
            res.setdefault(ev, {}).setdefault(ds, {})[m] = {i: sc for (i, _, _), sc in zip(rows, scores)}
            ITEMS.write_text(json.dumps(res), encoding="utf-8")
            print(ev, ds, m, len(rows), flush=True)
        model.unload()
    return res


def compare(res: dict) -> dict:
    out = {}
    for ev in F.EVALUATORS:
        for ds in F.DATASETS:
            rv = res[ev][ds]["ragverify"]
            entry = {}
            for m, name in METHODS:
                b = res[ev][ds][m]
                common = sorted(set(rv) & set(b))
                ua = np.array([rv[i] < 0.5 for i in common], float)
                ub = np.array([b[i] < 0.5 for i in common], float)
                d = paired_bootstrap(ua, ub)
                boots = None
                # two-sided bootstrap p for the difference in means
                rng = np.random.default_rng(0)
                idx = rng.integers(0, len(common), size=(10_000, len(common)))
                boots = (ua - ub)[idx].mean(1)
                d["p"] = float(min(1.0, 2 * min((boots <= 0).mean(), (boots >= 0).mean())))
                entry[m] = {"name": name, "n_common": len(common), "rv_rate": float(ua.mean()), "b_rate": float(ub.mean()), "diff": d}
            adj = holm({m: entry[m]["diff"]["p"] for m, _ in METHODS})
            for m, _ in METHODS:
                entry[m]["diff"]["p_holm"] = adj[m]
            out.setdefault(ev, {})[ds] = entry
    return out


def table(out: dict) -> None:
    f = lambda x: f"{x:+.3f}".replace("-", "$-$")  # noqa: E731
    L = ["% generated by analysis/faithfulness_paired.py (post-hoc P3): " + METHOD_NAME + " minus baseline unsupported rate on items "
         "answered by both (n in parentheses), each judged against its own evidence; 95% paired-bootstrap CI; * Holm p < 0.05",
         "\\begin{tabular}{@{}ll" + "c" * len(F.DATASETS) + "@{}}",
         "\\toprule Judge & vs. & " + " & ".join(DS_NAME[d] for d in F.DATASETS) + " \\\\ \\midrule"]
    for ev, jn in zip(F.EVALUATORS, ("AlignScore-L", "DeBERTa NLI")):
        for k, (m, name) in enumerate(METHODS):
            cells = []
            for ds in F.DATASETS:
                e = out[ev][ds][m]
                d = e["diff"]
                cells.append(f"{f(d['diff'])} [{f(d['ci_low'])}, {f(d['ci_high'])}]{'$^{*}$' if d['p_holm'] < 0.05 else ''} ({e['n_common']})")
            L.append(f"{jn if k == 0 else ''} & {name} & " + " & ".join(cells) + " \\\\")
        L.append("\\addlinespace")
    L[-1:] = ["\\bottomrule", "\\end{tabular}"]
    (ROOT / "paper" / "generated" / "table_faithfulness_paired.tex").write_text("\n".join(L) + "\n", encoding="utf-8")


if __name__ == "__main__":
    r = score_all()
    o = compare(r)
    (ROOT / "results" / "analysis" / "faithfulness_paired.json").write_text(json.dumps(o, indent=1), encoding="utf-8")
    table(o)
    print("ok")

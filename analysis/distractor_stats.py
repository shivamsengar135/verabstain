"""HotpotQA distractor experiment (PROTOCOL §11; specification in §17 entry 2026-11-05 15:10).

For each method and distractor level (0/25/50/75%): accuracy, hallucination at coverage 0.8 and AURC on the same 300
items, plus the accuracy drop from 0% to each level with a paired-bootstrap 95% CI (10,000 resamples, seed 0), and
RAG-Verify minus each baseline at every level (paired bootstrap CI). Only finished runs are used.
Usage: .venv/Scripts/python.exe analysis/distractor_stats.py -> results/analysis/distractor_stats.json,
       paper/generated/table_distractor.tex, paper/figures/distractor_accuracy.pdf
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))
sys.path.insert(0, str(ROOT / "analysis"))
from ragverify.metrics import paired_bootstrap  # noqa: E402
from main_stats import load_run, metrics  # noqa: E402
from phase4_stats import ready  # noqa: E402
from method_name import METHOD_NAME  # noqa: E402

LEVELS = [0, 25, 50, 75]
METHODS = [(METHOD_NAME, "ragverify"), ("B2 RAG top-k", "rag_topk"), ("B3 RAG + reranker", "rag_rerank"),
           ("B5 CRAG", "crag"), ("B6 Chain-of-Note", "chain_of_note"), ("B8 Self-RAG", "selfrag")]


def main() -> None:
    res = {"methods": {}, "missing": []}
    data = {}
    for _, m in METHODS:
        for p in LEVELS:
            rid = f"rob_{m}_hotpotqa_dist{p:02d}"
            if ready(rid):
                data[(m, p)] = load_run(rid, m)
            else:
                res["missing"].append(rid)
    for _, m in METHODS:
        r = {}
        for p in LEVELS:
            if (m, p) not in data:
                continue
            _, ids, c, s = data[(m, p)]
            r[str(p)] = metrics(c, s)
            if (m, 0) in data and p:
                _, ids0, c0, _ = data[(m, 0)]
                assert ids0 == ids
                r[str(p)]["acc_change_vs_0"] = paired_bootstrap(c, c0)
            if m != "ragverify" and ("ragverify", p) in data:
                _, idr, cr, _ = data[("ragverify", p)]
                assert idr == ids
                r[str(p)]["ragverify_minus_this_acc"] = paired_bootstrap(cr, c)
        res["methods"][m] = r
    (ROOT / "results" / "analysis").mkdir(exist_ok=True)
    (ROOT / "results" / "analysis" / "distractor_stats.json").write_text(json.dumps(res, indent=1), encoding="utf-8")

    L = ["% generated by analysis/distractor_stats.py: HotpotQA (300 items), accuracy / hallucination at coverage 0.8 per distractor level",
         "\\begin{tabular}{@{}l" + "c" * len(LEVELS) + "@{}}", "\\toprule Method & " + " & ".join(f"{p}\\%" for p in LEVELS) + " \\\\ \\midrule"]
    for name, m in METHODS:
        cells = [f"{e['accuracy']:.3f} / {e['halluc@0.8']:.3f}" if (e := res["methods"][m].get(str(p))) else "--" for p in LEVELS]
        L.append(f"{name} & " + " & ".join(cells) + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}"]
    (ROOT / "paper" / "generated" / "table_distractor.tex").write_text("\n".join(L) + "\n", encoding="utf-8")

    fig, ax = plt.subplots(figsize=(4.2, 3.0))
    for name, m in METHODS:
        pts = [(p, res["methods"][m][str(p)]["accuracy"]) for p in LEVELS if str(p) in res["methods"][m]]
        if pts:
            ax.plot(*zip(*pts), marker="*" if m == "ragverify" else "o", color="black" if m == "ragverify" else None,
                    label=name, linewidth=1.5 if m == "ragverify" else 1)
    ax.set_xlabel("Distractor passages (% of 5)", fontsize=8)
    ax.set_ylabel("Accuracy", fontsize=8)
    ax.tick_params(labelsize=7)
    ax.legend(fontsize=6)
    fig.tight_layout()
    (ROOT / "paper" / "figures").mkdir(exist_ok=True)
    fig.savefig(ROOT / "paper" / "figures" / "distractor_accuracy.pdf")
    print("missing", len(res["missing"]))


if __name__ == "__main__":
    main()

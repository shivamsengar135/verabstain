"""Efficiency analysis (PROTOCOL §8 efficiency metrics, §13): mean cost per example for every main run, and the
cost-quality Pareto plots (accuracy and hallucination at coverage 0.8 vs LLM calls and attributed LLM seconds).
Costs include cached calls (attributed per example), so every method is costed as if run from scratch.
Inputs: results/main_*/summary.json (scripts/score.py), results/analysis/main_stats.json (analysis/main_stats.py).
Usage: .venv/Scripts/python.exe analysis/efficiency.py -> paper/generated/table_efficiency.tex, paper/figures/pareto_*.pdf
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "analysis"))
from main_stats import BASELINES, DATASETS, DS_NAME  # noqa: E402
from method_name import METHOD_NAME  # noqa: E402

METHODS = [(METHOD_NAME, "ragverify")] + [(f"{b} {n}", m) for b, n, m in BASELINES if b not in ("A1", "A2")] + [("A2 B2 + SelfCheck", "rag_selfcheck")]
KEYS = [("mean_llm_calls", "LLM calls", 2), ("mean_prompt_tokens", "Prompt tok.", 0), ("mean_completion_tokens", "Compl. tok.", 0),
        ("mean_retrievals", "Retrievals", 2), ("mean_verifier_pairs", "Verifier pairs", 2), ("mean_llm_seconds", "LLM s", 2)]


def summ(m: str, ds: str) -> dict:
    return json.loads((ROOT / "results" / f"main_{m}_{ds}" / "summary.json").read_text(encoding="utf-8"))


def main() -> None:
    L = ["% generated by analysis/efficiency.py: mean cost per example, averaged over the 5 test datasets (each dataset weighted equally)",
         "\\begin{tabular}{@{}l" + "r" * len(KEYS) + "@{}}", "\\toprule Method & " + " & ".join(k[1] for k in KEYS) + " \\\\ \\midrule"]
    for name, m in METHODS:
        vals = [sum(summ(m, d)[k] for d in DATASETS) / len(DATASETS) for k, _, _ in KEYS]
        L.append(f"{name} & " + " & ".join(f"{v:.{p}f}" for v, (_, _, p) in zip(vals, KEYS)) + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}"]
    (ROOT / "paper" / "generated" / "table_efficiency.tex").write_text("\n".join(L) + "\n", encoding="utf-8")

    st = json.loads((ROOT / "results" / "analysis" / "main_stats.json").read_text(encoding="utf-8"))["datasets"]
    figdir = ROOT / "paper" / "figures"
    figdir.mkdir(parents=True, exist_ok=True)
    for qk, ql in (("accuracy", "Accuracy"), ("halluc@0.8", "Hallucination rate at coverage 0.8")):
        fig, axes = plt.subplots(1, len(DATASETS), figsize=(3.2 * len(DATASETS), 3.0), sharey=False)
        for ax, d in zip(axes, DATASETS):
            for name, m in METHODS:
                q = st[d]["ragverify"][qk] if m == "ragverify" else next(e[qk] for e in st[d]["baselines"].values() if e["run"] == f"main_{m}_{d}")
                c = summ(m, d)["mean_llm_calls"]
                ax.scatter(c, q, s=36 if m == "ragverify" else 18, marker="*" if m == "ragverify" else "o",
                           color="black" if m == "ragverify" else "tab:gray")
                ax.annotate(name.split(" ")[0], (c, q), fontsize=6, xytext=(2, 2), textcoords="offset points")
            ax.set_title(DS_NAME[d], fontsize=9)
            ax.set_xlabel("LLM calls / example", fontsize=8)
            ax.tick_params(labelsize=7)
        axes[0].set_ylabel(ql, fontsize=8)
        fig.tight_layout()
        fig.savefig(figdir / f"pareto_{qk.replace('@', '_at_')}.pdf")
        plt.close(fig)
    print("ok")


if __name__ == "__main__":
    main()

"""Generate paper/generated/setup_macros.tex from the frozen configuration and data splits (Rule 2: no hand-typed
numbers). Usage: .venv/Scripts/python.exe scripts/make_paper_macros.py"""
import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
cfg = yaml.safe_load((ROOT / "jobs" / "config.yaml").read_text(encoding="utf-8"))
main = yaml.safe_load((ROOT / "jobs" / "queue_main.yaml").read_text(encoding="utf-8"))
m6 = json.loads((ROOT / "analysis" / "m6_score_model.json").read_text(encoding="utf-8"))

out = {}
for key in ("k", "k_large", "k_sub", "pool_each", "pool_size", "max_answer_tokens", "max_draft_tokens",
            "max_query_tokens", "max_evidence", "sup_tau", "rounds", "selfcheck_samples", "flare_theta",
            "flare_beta", "flare_rounds", "crag_upper", "crag_lower", "selfrag_threshold", "rarr_max_questions"):
    out["cfg" + key.replace("_", " ").title().replace(" ", "")] = cfg[key]
sizes = {}
for j in main:
    if j["method"] == "closed_book":
        n = j["n"] or sum(1 for _ in (ROOT / "data" / "splits" / f"{j['dataset']}_test.ids").open(encoding="utf-8") if _.strip())
        sizes[j["dataset"]] = n
names = {"popqa_lt": "PopQA", "triviaqa": "TriviaQA", "hotpotqa": "HotpotQA", "pubhealth": "PubHealth", "rgb": "RGB"}
for d, n in sizes.items():
    out["nTest" + names[d]] = f"{n:,}"
out["nTestTotal"] = f"{sum(sizes.values()):,}"
out["nMainJobs"] = len(main)
out["mSixFeatures"] = len(m6["logistic"]["coef"])

lines = ["% generated by scripts/make_paper_macros.py -- do not edit"]
for k, v in out.items():
    lines.append(f"\\newcommand{{\\{k}}}{{{v}}}")
p = ROOT / "paper" / "generated" / "setup_macros.tex"
p.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(p.read_text(encoding="utf-8"))

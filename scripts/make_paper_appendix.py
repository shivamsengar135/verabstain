def data_appendix() -> str:
    from ragverify import data as D
    md = (ROOT / "logs" / "protocol_freeze" / "PROTOCOL.md").read_text(encoding="utf-8")
    sec = section(md, "2. Datasets")
    rows = [l for l in sec.splitlines() if l.startswith("| ") and not l.startswith("| Dataset") and "---" not in l]
    out = ["% generated by scripts/make_paper_appendix.py from the frozen PROTOCOL.md §2 and data/processed, data/splits",
           r"\begin{small}\begin{longtable}{@{}p{0.11\linewidth}p{0.25\linewidth}p{0.08\linewidth}p{0.22\linewidth}"
           r"p{0.07\linewidth}p{0.11\linewidth}p{0.1\linewidth}@{}}",
           r"\toprule Dataset & Test pool (source) & N test & Dev source & N dev & Passages & Primary metric \\ \midrule"]
    for r in rows:
        out.append(" & ".join(md_inline(c.strip()) for c in r.strip().strip("|").split("|")) + r" \\")
    out += [r"\bottomrule", r"\end{longtable}\end{small}", "",
            r"\paragraph{Dev/test disjointness (computed)} For each dataset with a development split, the number of development "
            "items whose id or normalised question text (lower-cased, alphanumerics only) also occurs among the test items used: "]
    items = []
    for name, n in (("popqa_lt", 1000), ("triviaqa", 1000), ("hotpotqa", 1000), ("pubhealth", None)):
        te, dv = D.load(name, "test", n), D.load(name, "dev")
        tid, tq = {e["id"] for e in te}, {_norm(e["question"]) for e in te}
        ov_id = sum(e["id"] in tid for e in dv)
        ov_q = sum(_norm(e["question"]) in tq for e in dv)
        tans = {}
        for e in te:
            tans.setdefault(_norm(e["question"]), set()).update(_norm(a) for a in e["answers"])
        ov_a = sum(_norm(e["question"]) in tq and bool(tans[_norm(e["question"])] & {_norm(a) for a in e["answers"]}) for e in dv)
        items.append(f"{tex_escape(name)}: {len(dv)} dev / {len(te)} test, {ov_id} shared ids, {ov_q} shared question strings"
                     + (f" ({ov_a} of them with a shared gold answer)" if ov_q else ""))
    out[-1] += ("; ".join(items) + ". PopQA questions are generated from templates, so different entities that share a name "
                "(for example several television episodes titled ``Pilot'') yield identical question strings; the shared strings "
                "above belong to different PopQA items about different entities. RGB has no development split and was not used "
                "for tuning.")
    tail = [x for x in sec.split("\n\n") if x.startswith("Self-RAG's evaluation files")]
    if tail:
        t = tail[0].replace("\n", " ").replace("; the user should check it once against the original if possible (TODO-VERIFY)", "")
        out += ["", md_inline(t)]
    out += ["", r"\paragraph{Licences} " + LICENCE_TEXT]
    return "\n".join(out) + "\n"


def versions() -> str:
    """Software versions (installed packages, read at generation time) and model sources (logs/downloads_manifest.tsv)."""
    import csv
    import importlib.metadata as im
    import platform
    pk = []
    for p in ("torch", "transformers", "sentence-transformers", "faiss-cpu", "bm25s", "numpy", "scipy", "scikit-learn"):
        try:
            pk.append(f"{p} {im.version(p)}")
        except im.PackageNotFoundError:
            pass
    env = (ROOT / "ENVIRONMENT.md").read_text(encoding="utf-8")
    m = re.search(r"llama\.cpp build (b\d+)\*\* \(commit (\w+)", env)
    llama = f"llama.cpp {m.group(1)} (commit {m.group(2)})" if m else "llama.cpp (see ENVIRONMENT.md)"
    rows = {}
    with (ROOT / "logs" / "downloads_manifest.tsv").open(encoding="utf-8") as f:
        for r in csv.DictReader(f, delimiter="\t"):
            if r["source"].startswith("hf:model:"):
                rows.setdefault(r["source"][9:], r["revision"][:10])
    out = ["% generated by scripts/make_paper_appendix.py (installed package versions; logs/downloads_manifest.tsv)",
           f"\\paragraph{{Software}} Python {platform.python_version()}; {tex_escape(llama)}; " + tex_escape(", ".join(pk)) + ".",
           "", "\\paragraph{Model checkpoints (Hugging Face repository, revision)}",
           "\\begin{small}\\begin{longtable}{@{}ll@{}}", "\\toprule Repository & Revision \\\\ \\midrule"]
    out += [f"\\texttt{{{tex_escape(k)}}} & \\texttt{{{v}}} \\\\" for k, v in sorted(rows.items())]
    out += ["\\bottomrule", "\\end{longtable}\\end{small}"]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    for name, fn in (("appendix_prompts", prompts), ("appendix_baselines", baselines), ("appendix_deviations", deviations),
                     ("appendix_data", data_appendix), ("appendix_versions", versions)):
        txt = fn()
        (GEN / f"{name}.tex").write_text(txt, encoding="utf-8")
        print(name, len(txt.splitlines()), "lines")
